/** نرمال‌سازی متن فارسی برای جستجو (ی/ک عربی، نیم‌فاصله، اعراب) */
export const faNormalize = (s: string) =>
  s
    .replace(/[\u064A\u0649]/g, "\u06CC")
    .replace(/\u0643/g, "\u06A9")
    .replace(/[\u200c\u200f\u200e]/g, " ")
    .replace(/[\u064B-\u0652]/g, "")
    .replace(/\s+/g, " ")
    .trim();
